/**
 * Server-side file generators for VELORIS chat.
 * Each function returns a Buffer ready to be sent to the client.
 */

import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, Table, TableRow, TableCell, WidthType, BorderStyle, ShadingType } from "docx";
import * as XLSX from "xlsx";
// @ts-ignore — pptxgenjs has incomplete type declarations
import PptxGenJS from "pptxgenjs";
import PDFDocument from "pdfkit";

export type FileGenResult = {
  buffer: Buffer;
  mime: string;
  filename: string;
};

// ── Helpers ─────────────────────────────────────────────────────────────────

function safeText(s: unknown): string {
  if (s == null) return "";
  return String(s).trim();
}

// ── DOCX ────────────────────────────────────────────────────────────────────

export type DocxSpec = {
  title?: string;
  sections: Array<{
    heading?: string;
    level?: 1 | 2 | 3;
    paragraphs: string[];
  }>;
};

export async function generateDocx(spec: DocxSpec, filename = "document"): Promise<FileGenResult> {
  const children: Paragraph[] = [];

  if (spec.title) {
    children.push(
      new Paragraph({
        text: spec.title,
        heading: HeadingLevel.TITLE,
        alignment: AlignmentType.CENTER,
        spacing: { after: 400 },
      })
    );
  }

  for (const sec of spec.sections) {
    if (sec.heading) {
      const level = sec.level === 2 ? HeadingLevel.HEADING_2 : sec.level === 3 ? HeadingLevel.HEADING_3 : HeadingLevel.HEADING_1;
      children.push(new Paragraph({ text: sec.heading, heading: level, spacing: { before: 300, after: 150 } }));
    }
    for (const para of sec.paragraphs) {
      children.push(new Paragraph({ text: para, spacing: { after: 100 } }));
    }
  }

  const doc = new Document({
    sections: [{ properties: {}, children }],
    creator: "VELORIS AI",
    description: spec.title || "Generated by VELORIS",
  });

  const buffer = Buffer.from(await Packer.toBuffer(doc));
  return { buffer, mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document", filename: `${filename}.docx` };
}

// ── XLSX ─────────────────────────────────────────────────────────────────────

export type XlsxSpec = {
  sheets: Array<{
    name: string;
    headers: string[];
    rows: (string | number | boolean | null)[][];
  }>;
};

export function generateXlsx(spec: XlsxSpec, filename = "spreadsheet"): FileGenResult {
  const wb = XLSX.utils.book_new();

  for (const sheet of spec.sheets) {
    const data = [sheet.headers, ...sheet.rows];
    const ws = XLSX.utils.aoa_to_sheet(data);

    // Auto column widths
    const colWidths = sheet.headers.map((h, i) => {
      const maxLen = Math.max(
        h.length,
        ...sheet.rows.map(r => safeText(r[i]).length)
      );
      return { wch: Math.min(50, maxLen + 2) };
    });
    ws["!cols"] = colWidths;

    XLSX.utils.book_append_sheet(wb, ws, sheet.name.slice(0, 31));
  }

  const buffer = Buffer.from(XLSX.write(wb, { type: "buffer", bookType: "xlsx" }));
  return { buffer, mime: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", filename: `${filename}.xlsx` };
}

export function generateCsv(headers: string[], rows: (string | number | null)[][], filename = "data"): FileGenResult {
  const escape = (v: unknown) => {
    const s = safeText(v);
    return s.includes(",") || s.includes('"') || s.includes("\n") ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = [[...headers].map(escape).join(","), ...rows.map(r => r.map(escape).join(","))];
  const buffer = Buffer.from(lines.join("\n"), "utf-8");
  return { buffer, mime: "text/csv", filename: `${filename}.csv` };
}

// ── PPTX ─────────────────────────────────────────────────────────────────────

export type PptxSlide = {
  title: string;
  content?: string;
  bullets?: string[];
  notes?: string;
};

export async function generatePptx(slides: PptxSlide[], title = "Presentation", filename = "presentation"): Promise<FileGenResult> {
  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_16x9";
  pptx.author = "VELORIS AI";
  pptx.title = title;

  // Title slide
  const titleSlide = pptx.addSlide();
  titleSlide.background = { fill: "0a0a0a" };
  titleSlide.addText(title, {
    x: 0.5, y: 2.5, w: 9, h: 1.5,
    fontSize: 40, bold: true, color: "c9a227",
    align: "center", fontFace: "Calibri",
  });
  titleSlide.addText("Generated by VELORIS AI", {
    x: 0.5, y: 4.2, w: 9, h: 0.5,
    fontSize: 14, color: "888888", align: "center",
  });

  // Content slides
  for (const s of slides) {
    const slide = pptx.addSlide();
    slide.background = { fill: "050505" };

    // Title bar
    slide.addText(s.title, {
      x: 0.4, y: 0.3, w: 9.2, h: 0.9,
      fontSize: 24, bold: true, color: "c9a227",
      fontFace: "Calibri",
    });

    // Divider line
    slide.addShape(pptx.ShapeType.rect, { x: 0.4, y: 1.3, w: 9.2, h: 0.03, fill: { color: "333333" } });

    if (s.bullets && s.bullets.length > 0) {
      const bulletItems = s.bullets.map(b => ({ text: b, options: { bullet: { indent: 15 }, paraSpaceAfter: 6 } }));
      slide.addText(bulletItems, {
        x: 0.6, y: 1.5, w: 8.8, h: 4.5,
        fontSize: 16, color: "e0e0e0", fontFace: "Calibri",
        valign: "top",
      });
    } else if (s.content) {
      slide.addText(s.content, {
        x: 0.6, y: 1.5, w: 8.8, h: 4.5,
        fontSize: 16, color: "e0e0e0", fontFace: "Calibri",
        valign: "top", wrap: true,
      });
    }

    if (s.notes) slide.addNotes(s.notes);
  }

  const arrayBuffer = await pptx.write({ outputType: "arraybuffer" });
  const buffer = Buffer.from(arrayBuffer as ArrayBuffer);
  return { buffer, mime: "application/vnd.openxmlformats-officedocument.presentationml.presentation", filename: `${filename}.pptx` };
}

// ── PDF ───────────────────────────────────────────────────────────────────────

export type PdfSpec = {
  title?: string;
  sections: Array<{ heading?: string; paragraphs: string[] }>;
};

export function generatePdf(spec: PdfSpec, filename = "document"): Promise<FileGenResult> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    const doc = new PDFDocument({ margin: 60, size: "A4" });

    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("error", reject);
    doc.on("end", () => {
      const buffer = Buffer.concat(chunks);
      resolve({ buffer, mime: "application/pdf", filename: `${filename}.pdf` });
    });

    // Header
    if (spec.title) {
      doc.fontSize(28).fillColor("#c9a227").font("Helvetica-Bold").text(spec.title, { align: "center" });
      doc.moveDown(0.5);
      doc.moveTo(60, doc.y).lineTo(doc.page.width - 60, doc.y).strokeColor("#333333").stroke();
      doc.moveDown(1);
    }

    for (const sec of spec.sections) {
      if (sec.heading) {
        doc.fontSize(16).fillColor("#c9a227").font("Helvetica-Bold").text(sec.heading);
        doc.moveDown(0.3);
      }
      for (const para of sec.paragraphs) {
        doc.fontSize(11).fillColor("#333333").font("Helvetica").text(para, { lineGap: 4 });
        doc.moveDown(0.5);
      }
    }

    // Footer
    doc.fontSize(9).fillColor("#999999").text("Generated by VELORIS AI", { align: "center" });
    doc.end();
  });
}

// ── Plain text formats ────────────────────────────────────────────────────────

export function generateTxt(content: string, filename = "file"): FileGenResult {
  return { buffer: Buffer.from(content, "utf-8"), mime: "text/plain", filename: `${filename}.txt` };
}

export function generateJson(data: unknown, filename = "data"): FileGenResult {
  const content = typeof data === "string" ? data : JSON.stringify(data, null, 2);
  return { buffer: Buffer.from(content, "utf-8"), mime: "application/json", filename: `${filename}.json` };
}

export function generateXml(content: string, filename = "data"): FileGenResult {
  return { buffer: Buffer.from(content, "utf-8"), mime: "application/xml", filename: `${filename}.xml` };
}

export function generateCode(content: string, extension: string, filename = "code"): FileGenResult {
  const mimes: Record<string, string> = {
    py: "text/x-python", js: "text/javascript", ts: "text/typescript",
    html: "text/html", css: "text/css", sql: "application/sql",
    java: "text/x-java", cpp: "text/x-c++src", php: "application/x-php",
    lua: "text/x-lua", sh: "text/x-shellscript", rs: "text/x-rust",
    go: "text/x-go", md: "text/markdown", yaml: "text/yaml",
    toml: "text/x-toml", rb: "text/x-ruby", kt: "text/x-kotlin",
    swift: "text/x-swift", dart: "text/x-dart",
  };
  const mime = mimes[extension] || "text/plain";
  return { buffer: Buffer.from(content, "utf-8"), mime, filename: `${filename}.${extension}` };
}

// ── ZIP archive ───────────────────────────────────────────────────────────────

import JSZip from "jszip";

export async function generateZip(files: Record<string, string | Buffer>, filename = "project"): Promise<FileGenResult> {
  const zip = new JSZip();
  for (const [path, content] of Object.entries(files)) {
    zip.file(path, content);
  }
  const buffer = Buffer.from(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
  return { buffer, mime: "application/zip", filename: `${filename}.zip` };
}

