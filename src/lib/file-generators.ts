export function generateRbxlx(placeName: string, scripts: Record<string, string>, filename = "place"): FileGenResult {
  // Minimal Roblox XML place format
  const scriptElements = Object.entries(scripts).map(([name, source]) => `
    <Item class="Script" referent="script_${name.replace(/\W/g, "_")}">
      <Properties>
        <string name="Name">${name}</string>
        <ProtectedString name="Source"><![CDATA[${source}]]></ProtectedString>
        <bool name="Disabled">false</bool>
      </Properties>
    </Item>`).join("\n");

  const rbxl = `<?xml version="1.0" encoding="utf-8"?>
<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">
  <External>null</External>
  <External>nil</External>
  <Item class="DataModel" referent="RBX0">
    <Properties>
      <string name="Name">${placeName}</string>
    </Properties>
    <Item class="Workspace" referent="RBX1">
      <Properties>
        <string name="Name">Workspace</string>
      </Properties>
    </Item>
    <Item class="ServerScriptService" referent="RBX2">
      <Properties>
        <string name="Name">ServerScriptService</string>
      </Properties>
      ${scriptElements}
    </Item>
    <Item class="StarterGui" referent="RBX3">
      <Properties>
        <string name="Name">StarterGui</string>
      </Properties>
    </Item>
    <Item class="StarterPack" referent="RBX4">
      <Properties>
        <string name="Name">StarterPack</string>
      </Properties>
    </Item>
  </Item>
</roblox>`;

  return { buffer: Buffer.from(rbxl, "utf-8"), mime: "application/xml", filename: `${filename}.rbxlx` };
}

